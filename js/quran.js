const PAGE_STARTS = (() => {
  const out = [];
  for (const seg of PAGE_STARTS_ENC.split(';')) {
    const [s, list] = seg.split(':');
    for (const a of list.split(',')) out.push(+s * 1000 + +a);
  }
  return out;
})();

export function pageOfAyah(sura, ayah) {
  const key = sura * 1000 + (ayah || 1);
  let lo = 0, hi = PAGE_STARTS.length - 1, ans = 0;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (PAGE_STARTS[mid] <= key) { ans = mid; lo = mid + 1; } else hi = mid - 1;
  }
  return ans + 1;
}

